"""`booking_documents` collection: metadata of booking PDFs stored in GridFS.

The PDF bytes live in the GridFS bucket `booking_pdfs` (collections
`booking_pdfs.files` / `booking_pdfs.chunks`); this document points to them with
`file_id`. `source` says who produced the PDF:

- "app_confirmation": generated by this app from the provider's confirmed booking
  record. It is NOT a supplier voucher or invoice, and is labelled as such.
- "provider_voucher": an official document issued by the provider (Nuitee does not
  supply one today; kept for providers that do).

(booking_id, source) is unique, so retries never store a second copy.
"""
from __future__ import annotations

from datetime import datetime
from typing import Any, ClassVar, Literal

from pydantic import BaseModel, ConfigDict, Field
from pymongo import ASCENDING, DESCENDING, IndexModel

from models.conversation import PyObjectId, _utcnow

GRIDFS_BUCKET = "booking_pdfs"


class BookingDocument(BaseModel):
    model_config = ConfigDict(populate_by_name=True, arbitrary_types_allowed=True,
                              extra="forbid", str_strip_whitespace=True)

    collection_name: ClassVar[str] = "booking_documents"
    indexes: ClassVar[list[IndexModel]] = [
        IndexModel([("booking_id", ASCENDING), ("source", ASCENDING)], unique=True,
                   name="booking_source_unique"),
        IndexModel([("user_id", ASCENDING), ("created_at", DESCENDING)],
                   name="user_id_created_at"),
    ]

    id: PyObjectId = Field(alias="_id")
    booking_id: PyObjectId                   # -> bookings._id
    user_id: PyObjectId                      # -> users._id
    conversation_id: PyObjectId              # -> conversations._id
    provider_booking_id: str
    source: Literal["app_confirmation", "provider_voucher"]
    label: str                               # shown to the user, e.g. "Booking confirmation"
    bucket: str = GRIDFS_BUCKET
    file_id: PyObjectId                      # -> booking_pdfs.files._id
    filename: str
    content_type: str = "application/pdf"
    size: int
    sha256: str
    created_at: datetime = Field(default_factory=_utcnow)

    def to_document(self) -> dict[str, Any]:
        return self.model_dump(by_alias=True)
